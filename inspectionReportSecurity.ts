import { sessionMatches } from './sessionSecurity.js';
export class InspectionSubmissionError extends Error {
  constructor(message: string, public status: number) { super(message); }
}

/** Recheck the current officer record, even if a stale user copy still has a token. */
export function activeOfficerAccount(actor: any, officers: any[]): any | undefined {
  const profile = actor?.user || actor;
  if (profile?.role !== 'verification_team' || !profile.id) return undefined;
  const matches = officers.filter(officer => officer.id === profile.id);
  return matches.length === 1 && matches[0].status === 'active' ? matches[0] : undefined;
}
export function currentReportOfficer(actor: any, officers: any[]): any | undefined {
  const officer = activeOfficerAccount(actor, officers);
  return officer && sessionMatches(officer, actor?.token) ? officer : undefined;
}

export function officerIsAssigned(officer: any, record: any): boolean {
  const assignedId = record?.assignedOfficerId;
  return Boolean(officer?.id && typeof assignedId === 'string' && assignedId &&
    (assignedId === officer.id || officer.officerId && assignedId === officer.officerId));
}

/** Resolve stored IDs only. Display-list merges, emails and default officers are not authority. */
export function inspectionSubmissionTarget(id: string, inspections: any[], verifications: any[], officer: any): { inspection: any; verification?: any } {
  const verificationIds = [id, ...(id.startsWith('insp-') ? [id.slice(5)] : [])];
  let matches = inspections.filter(inspection => inspection.id === id);
  if (!matches.length) matches = inspections.filter(inspection => verificationIds.includes(inspection.managerVerificationId));
  if (matches.length > 1) throw new InspectionSubmissionError('Inspection assignment is ambiguous; request an administrator dispatch', 409);
  let inspection = matches[0];
  const linkedId = inspection?.managerVerificationId;
  const linked = verifications.filter(verification => inspection
    ? Boolean(linkedId && verification.id === linkedId)
    : verificationIds.includes(verification.id));
  if (linked.length > 1) throw new InspectionSubmissionError('Verification assignment is ambiguous', 409);
  const verification = linked[0];
  if (!inspection && !verification) throw new InspectionSubmissionError('Inspection record not found', 404);
  if (!inspection) {
    if (!officerIsAssigned(officer, verification)) throw new InspectionSubmissionError('You are not assigned to this inspection', 403);
    // Support dispatched legacy verification records without inventing an officer or property.
    inspection = {
      id: `insp-${verification.id}`, managerVerificationId: verification.id,
      managerName: verification.managerName, managerEmail: verification.managerEmail,
      managerPhone: verification.managerPhone,
      hostelName: verification.hostelName || verification.residenceName,
      location: verification.location || verification.address,
      dispatchedAt: verification.dispatchedAt, dispatchedBy: verification.dispatchedBy,
      assignedOfficerId: verification.assignedOfficerId,
      assignedOfficerName: officer.fullName, assignedOfficerEmail: officer.email,
      status: verification.inspectionStatus || 'dispatched',
      priority: verification.priority, report: null
    };
  }
  if (!officerIsAssigned(officer, inspection) || verification?.assignedOfficerId && !officerIsAssigned(officer, verification)) {
    throw new InspectionSubmissionError('You are not assigned to this inspection', 403);
  }
  if (['approved', 'rejected'].includes(inspection.status) || inspection.adminDecision ||
      ['approved', 'rejected'].includes(verification?.inspectionStatus)) {
    throw new InspectionSubmissionError('This inspection has already received an administrator decision', 409);
  }
  return { inspection: { ...inspection }, verification };
}

const CHECKLIST_FIELDS = ['residenceExists', 'managerConnected', 'basicPropertyInfoVerified', 'managerAuthorityConfirmed', 'generalLegitimacyConfirmed', 'safetyHabitableCompliance'];

/** Report authorship and timestamps are generated by the server, never taken from the body. */
export function buildInspectionReport(body: any, officer: any): any {
  if (!body || typeof body !== 'object' || Array.isArray(body) || typeof body.observations !== 'string' || body.observations.trim().length < 10) {
    throw new InspectionSubmissionError('Detailed field inspection observations are required (minimum 10 characters)', 400);
  }
  const recommendation = body.recommendation;
  if (!['recommend_approval', 'recommend_rejection', 'requires_reinspection', 'requires_followup'].includes(recommendation)) {
    throw new InspectionSubmissionError('Invalid inspection recommendation', 400);
  }
  const gps = body.gpsCoordinates;
  if (gps != null && (typeof gps !== 'object' || Array.isArray(gps) ||
      typeof gps.lat !== 'number' || !Number.isFinite(gps.lat) || Math.abs(gps.lat) > 90 ||
      typeof gps.lng !== 'number' || !Number.isFinite(gps.lng) || Math.abs(gps.lng) > 180)) {
    throw new InspectionSubmissionError('Invalid inspection coordinates', 400);
  }
  for (const field of ['checklist', 'propertyDetails']) {
    if (body[field] != null && (typeof body[field] !== 'object' || Array.isArray(body[field]))) {
      throw new InspectionSubmissionError('Invalid inspection details', 400);
    }
  }
  const checklist: Record<string, boolean> = {};
  for (const field of CHECKLIST_FIELDS) {
    const value = body.checklist?.[field];
    if (value !== undefined && typeof value !== 'boolean') throw new InspectionSubmissionError('Invalid inspection checklist', 400);
    checklist[field] = value ?? false;
  }
  const details = body.propertyDetails || {};
  for (const field of ['estimatedRooms', 'estimatedBeds']) {
    if (details[field] !== undefined && (typeof details[field] !== 'number' || !Number.isFinite(details[field]) || details[field] < 0)) {
      throw new InspectionSubmissionError('Invalid estimated property capacity', 400);
    }
  }
  for (const field of ['securityPresent', 'utilitiesOperational']) {
    if (details[field] !== undefined && typeof details[field] !== 'boolean') throw new InspectionSubmissionError('Invalid property details', 400);
  }
  if (details.buildingStructure !== undefined && typeof details.buildingStructure !== 'string') throw new InspectionSubmissionError('Invalid property description', 400);
  if (body.photos !== undefined && (!Array.isArray(body.photos) || body.photos.some((photo: any) => !photo || typeof photo.title !== 'string' || typeof photo.url !== 'string' || typeof photo.capturedAt !== 'string'))) {
    throw new InspectionSubmissionError('Invalid inspection photos', 400);
  }
  const now = new Date().toISOString();
  return {
    submittedAt: now, timestamp: now,
    officerId: officer.id, officerCode: officer.officerId,
    officerName: officer.fullName, officerEmail: officer.email,
    gpsCoordinates: gps ? { lat: gps.lat, lng: gps.lng, ...(typeof gps.accuracyMeters === 'number' ? { accuracyMeters: gps.accuracyMeters } : {}), ...(typeof gps.capturedAddress === 'string' ? { capturedAddress: gps.capturedAddress } : {}) } : null,
    checklist,
    propertyDetails: {
      estimatedRooms: details.estimatedRooms ?? 0, estimatedBeds: details.estimatedBeds ?? 0,
      buildingStructure: details.buildingStructure ?? '',
      securityPresent: details.securityPresent ?? false, utilitiesOperational: details.utilitiesOperational ?? false
    },
    photos: (body.photos || []).map((photo: any) => ({ title: photo.title, url: photo.url, capturedAt: photo.capturedAt })),
    observations: body.observations.trim(), recommendation,
    inspectorSignature: `${officer.fullName} (${officer.officerId || officer.id})`
  };
}
